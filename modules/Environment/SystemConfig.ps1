#Requires -Version 5.1
<#
.SYNOPSIS
    PSManager Environment - System Configuration & Default Shell Management
#>

# Resolve from the module layout (<root>\modules\Environment\SystemConfig.ps1 -> <root>)
# so shortcuts and profile aliases point at the copy that is actually running.
$Script:ROOT_PATH = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$Script:CONHOST_DELEGATION = "{00000000-0000-0000-0000-000000000000}"

function Set-PowerShell7Default {
    [CmdletBinding()]
    [OutputType([System.Collections.Specialized.OrderedDictionary])]
    param(
        [switch]$Silent
    )

    $results = [ordered]@{}
    $status = Get-PSManagerStatus

    # 1. Windows Terminal Default Profile -> PS 7
    if ($status.WTSettingsPath -and $status.PS7Guid) {
        try {
            $raw = Get-Content $status.WTSettingsPath -Raw
            $json = $raw | ConvertFrom-Json
            $json.defaultProfile = $status.PS7Guid
            $json | ConvertTo-Json -Depth 10 | Set-Content $status.WTSettingsPath -Encoding UTF8
            $results['Windows Terminal Profile'] = "OK (Set default to PowerShell 7 [$($status.PS7Guid)])"
        } catch {
            $results['Windows Terminal Profile'] = "FAILED: $($_.Exception.Message)"
        }
    } else {
        $results['Windows Terminal Profile'] = "SKIPPED (Settings or PS7 profile not found)"
    }

    # 2. Windows 11 Default Terminal Host -> Windows Terminal
    try {
        $regKey = 'HKCU:\Console\%%Startup'
        if (-not (Test-Path $regKey)) {
            New-Item -Path $regKey -Force | Out-Null
        }
        Set-ItemProperty -Path $regKey -Name 'DelegationConsole' -Value $Script:WT_DELEGATION_CONSOLE -Force
        Set-ItemProperty -Path $regKey -Name 'DelegationTerminal' -Value $Script:WT_DELEGATION_TERMINAL -Force
        $results['Windows 11 Default Terminal Host'] = "OK (Set to Windows Terminal)"
    } catch {
        $results['Windows 11 Default Terminal Host'] = "FAILED: $($_.Exception.Message)"
    }

    # 3. Command Shim: 'powershell' -> 'pwsh' in PATH
    try {
        if (-not (Test-Path $Script:USER_BIN_PATH)) {
            New-Item -ItemType Directory -Path $Script:USER_BIN_PATH -Force | Out-Null
        }
        $shimContent = "@echo off`r`nrem PowerShell 7 Redirection Shim generated by PSManager`r`npwsh.exe %*`r`n"
        Set-Content -Path "$Script:USER_BIN_PATH\powershell.cmd" -Value $shimContent -Encoding ASCII
        if (Test-Path $Script:LOCAL_BIN_PATH) {
            Set-Content -Path "$Script:LOCAL_BIN_PATH\powershell.cmd" -Value $shimContent -Encoding ASCII
        }

        # Fallback shim for legacy 5.1
        $winpsContent = "@echo off`r`nrem Legacy Windows PowerShell 5.1 launcher`r`n%SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe %*`r`n"
        Set-Content -Path "$Script:USER_BIN_PATH\winps.cmd" -Value $winpsContent -Encoding ASCII
        if (Test-Path $Script:LOCAL_BIN_PATH) {
            Set-Content -Path "$Script:LOCAL_BIN_PATH\winps.cmd" -Value $winpsContent -Encoding ASCII
        }
        $results['Command Redirection Shim'] = "OK (Created powershell.cmd -> pwsh.exe in user PATH; 'winps' launches PS 5.1)"
    } catch {
        $results['Command Redirection Shim'] = "FAILED: $($_.Exception.Message)"
    }

    # 4. VS Code Default Terminal Profile
    $vscodeParent = Split-Path $Script:VSCODE_SETTINGS
    if (Test-Path $vscodeParent) {
        try {
            $settings = @{}
            if (Test-Path $Script:VSCODE_SETTINGS) {
                $raw = Get-Content $Script:VSCODE_SETTINGS -Raw
                if ($raw.Trim()) { $settings = $raw | ConvertFrom-Json }
            }
            $settings | Add-Member -NotePropertyName 'terminal.integrated.defaultProfile.windows' -NotePropertyValue 'PowerShell 7' -Force
            $settings | ConvertTo-Json -Depth 10 | Set-Content $Script:VSCODE_SETTINGS -Encoding UTF8
            $results['VS Code Terminal Default'] = "OK (Set to PowerShell 7)"
        } catch {
            $results['VS Code Terminal Default'] = "FAILED: $($_.Exception.Message)"
        }
    }

    # 5. Explorer Context Menu ("Open PowerShell 7 Here" and .ps1 "Run with PS7")
    try {
        $pwshPath = if ($status.Installations.PS7) { $status.Installations.PS7.Path } else { "pwsh.exe" }
        
        # Background folder context menu
        $bgKey = 'HKCU:\Software\Classes\Directory\Background\shell\OpenPowerShell7'
        New-Item -Path $bgKey -Force | Out-Null
        Set-ItemProperty -Path $bgKey -Name '(default)' -Value 'Open in PowerShell 7' -Force
        Set-ItemProperty -Path $bgKey -Name 'Icon' -Value $pwshPath -Force
        $bgCmd = "$bgKey\command"
        New-Item -Path $bgCmd -Force | Out-Null
        Set-ItemProperty -Path $bgCmd -Name '(default)' -Value 'wt.exe -p "PowerShell 7" -d "%V"' -Force

        # Directory context menu
        $dirKey = 'HKCU:\Software\Classes\Directory\shell\OpenPowerShell7'
        New-Item -Path $dirKey -Force | Out-Null
        Set-ItemProperty -Path $dirKey -Name '(default)' -Value 'Open in PowerShell 7' -Force
        Set-ItemProperty -Path $dirKey -Name 'Icon' -Value $pwshPath -Force
        $dirCmd = "$dirKey\command"
        New-Item -Path $dirCmd -Force | Out-Null
        Set-ItemProperty -Path $dirCmd -Name '(default)' -Value 'wt.exe -p "PowerShell 7" -d "%1"' -Force

        # .ps1 script context menu
        $ps1Key = 'HKCU:\Software\Classes\SystemFileAssociations\.ps1\shell\RunPS7'
        New-Item -Path $ps1Key -Force | Out-Null
        Set-ItemProperty -Path $ps1Key -Name '(default)' -Value 'Run with PowerShell 7' -Force
        Set-ItemProperty -Path $ps1Key -Name 'Icon' -Value $pwshPath -Force
        $ps1Cmd = "$ps1Key\command"
        New-Item -Path $ps1Cmd -Force | Out-Null
        Set-ItemProperty -Path $ps1Cmd -Name '(default)' -Value "`"$pwshPath`" -NoProfile -ExecutionPolicy Bypass -File `"%1`"" -Force

        $results['Explorer Context Menu'] = "OK (Added 'Open in PowerShell 7' and .ps1 'Run with PS7')"
    } catch {
        $results['Explorer Context Menu'] = "FAILED: $($_.Exception.Message)"
    }

    # 6. Shortcuts
    try {
        $wsh = New-Object -ComObject WScript.Shell
        $desktop = [Environment]::GetFolderPath('Desktop')
        $startMenu = "$env:APPDATA\Microsoft\Windows\Start Menu\Programs"
        foreach ($dir in @($desktop, $startMenu)) {
            $lnkTUI = $wsh.CreateShortcut("$dir\PSManager TUI.lnk")
            $lnkTUI.TargetPath = "wt.exe"
            $lnkTUI.Arguments = "-p `"PowerShell 7`" pwsh.exe -NoProfile -ExecutionPolicy Bypass -File `"$Script:ROOT_PATH\ps-manager.ps1`" tui"
            $lnkTUI.Description = "PowerShell Version Manager (TUI)"
            $lnkTUI.WorkingDirectory = $env:USERPROFILE
            $lnkTUI.Save()

            $lnkGUI = $wsh.CreateShortcut("$dir\PSManager Desktop.lnk")
            $lnkGUI.TargetPath = "powershell.exe"
            $lnkGUI.Arguments = "-WindowStyle Hidden -NoProfile -ExecutionPolicy Bypass -File `"$Script:ROOT_PATH\gui.ps1`""
            $lnkGUI.Description = "PowerShell Version Manager (Desktop GUI)"
            $lnkGUI.WorkingDirectory = $env:USERPROFILE
            $lnkGUI.Save()
        }
        $results['Shortcuts'] = "OK (Created Desktop & Start Menu TUI + GUI shortcuts)"
    } catch {
        $results['Shortcuts'] = "FAILED: $($_.Exception.Message)"
    }

    # 7. Profile integration
    try {
        Install-PSManagerProfileAliases
        $results['Profile Integration'] = "OK (Registered 'psmgr', 'psmgr-gui', 'ps7', 'winps' commands)"
    } catch {
        $results['Profile Integration'] = "FAILED: $($_.Exception.Message)"
    }

    if (-not $Silent) {
        Write-Host ""
        Write-Host (Color-Text ($Script:THEME.Green + $Script:THEME.Bold) "[SUCCESS] PowerShell 7 configured as DEFAULT shell!")
        Write-Host ""
        foreach ($k in $results.Keys) {
            Write-Host ("  " + (Color-Text $Script:THEME.Cyan "*") + " " + (Color-Text $Script:THEME.Bold $k) + ": " + $results[$k])
        }
    }
    return $results
}

function Set-PowerShell5Default {
    [CmdletBinding()]
    [OutputType([System.Collections.Specialized.OrderedDictionary])]
    param(
        [switch]$Silent
    )

    $results = [ordered]@{}
    $status = Get-PSManagerStatus

    # 1. Windows Terminal Default Profile -> PS 5.1
    if ($status.WTSettingsPath -and $status.PS5Guid) {
        try {
            $raw = Get-Content $status.WTSettingsPath -Raw
            $json = $raw | ConvertFrom-Json
            $json.defaultProfile = $status.PS5Guid
            $json | ConvertTo-Json -Depth 10 | Set-Content $status.WTSettingsPath -Encoding UTF8
            $results['Windows Terminal Profile'] = "OK (Restored to Windows PowerShell [$($status.PS5Guid)])"
        } catch {
            $results['Windows Terminal Profile'] = "FAILED: $($_.Exception.Message)"
        }
    }

    # 2. Reset Terminal Delegation -> ConHost / Default
    try {
        $regKey = 'HKCU:\Console\%%Startup'
        if (Test-Path $regKey) {
            Set-ItemProperty -Path $regKey -Name 'DelegationConsole' -Value $Script:CONHOST_DELEGATION -Force
            Set-ItemProperty -Path $regKey -Name 'DelegationTerminal' -Value $Script:CONHOST_DELEGATION -Force
        }
        $results['Windows 11 Default Terminal Host'] = "OK (Reset to Windows Console Host)"
    } catch {
        $results['Windows 11 Default Terminal Host'] = "FAILED: $($_.Exception.Message)"
    }

    # 3. Remove Command Shim
    try {
        $shims = @("$Script:USER_BIN_PATH\powershell.cmd", "$Script:LOCAL_BIN_PATH\powershell.cmd")
        foreach ($s in $shims) {
            if (Test-Path $s) { Remove-Item $s -Force }
        }
        $results['Command Redirection Shim'] = "OK (Removed powershell.cmd; native powershell.exe runs)"
    } catch {
        $results['Command Redirection Shim'] = "FAILED: $($_.Exception.Message)"
    }

    # 4. VS Code Default Profile
    if (Test-Path $Script:VSCODE_SETTINGS) {
        try {
            $raw = Get-Content $Script:VSCODE_SETTINGS -Raw
            $settings = $raw | ConvertFrom-Json
            $settings | Add-Member -NotePropertyName 'terminal.integrated.defaultProfile.windows' -NotePropertyValue 'Windows PowerShell' -Force
            $settings | ConvertTo-Json -Depth 10 | Set-Content $Script:VSCODE_SETTINGS -Encoding UTF8
            $results['VS Code Terminal Default'] = "OK (Restored to Windows PowerShell)"
        } catch {
            $results['VS Code Terminal Default'] = "FAILED: $($_.Exception.Message)"
        }
    }

    # 5. Remove Explorer Context Menu
    try {
        Remove-Item 'HKCU:\Software\Classes\Directory\Background\shell\OpenPowerShell7' -Recurse -Force -ErrorAction SilentlyContinue
        Remove-Item 'HKCU:\Software\Classes\Directory\shell\OpenPowerShell7' -Recurse -Force -ErrorAction SilentlyContinue
        Remove-Item 'HKCU:\Software\Classes\SystemFileAssociations\.ps1\shell\RunPS7' -Recurse -Force -ErrorAction SilentlyContinue
        $results['Explorer Context Menu'] = "OK (Removed PowerShell 7 context entries)"
    } catch {
        $results['Explorer Context Menu'] = "FAILED: $($_.Exception.Message)"
    }

    if (-not $Silent) {
        Write-Host ""
        Write-Host (Color-Text ($Script:THEME.Yellow + $Script:THEME.Bold) "[REVERTED] Windows PowerShell 5.1 restored as default.")
        Write-Host ""
        foreach ($k in $results.Keys) {
            Write-Host ("  " + (Color-Text $Script:THEME.Cyan "*") + " " + (Color-Text $Script:THEME.Bold $k) + ": " + $results[$k])
        }
    }
    return $results
}

function Install-PSManagerProfileAliases {
    [CmdletBinding()]
    param()

    $codeBlock = "`r`n# >>> PSManager Integration >>>`r`nfunction psmgr         { & `"$Script:ROOT_PATH\ps-manager.ps1`" @args }`r`nfunction Start-PsmgrGUI { Start-Process powershell.exe -ArgumentList `"-WindowStyle Hidden -NoProfile -ExecutionPolicy Bypass -File ````\`"$Script:ROOT_PATH\gui.ps1````\`"`" }`r`nSet-Alias -Name psmgr-gui -Value Start-PsmgrGUI -Force -ErrorAction SilentlyContinue`r`nfunction ps7           { & pwsh.exe @args }`r`nfunction winps         { & `"$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe`" @args }`r`n# <<< PSManager Integration <<<`r`n"
    $profiles = @(
        "$env:USERPROFILE\Documents\PowerShell\Microsoft.PowerShell_profile.ps1",
        "$env:USERPROFILE\Documents\WindowsPowerShell\Microsoft.PowerShell_profile.ps1"
    )
    foreach ($p in $profiles) {
        $dir = Split-Path $p
        if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
        $content = if (Test-Path $p) { Get-Content $p -Raw } else { "" }
        if ($content -notmatch 'PSManager Integration') {
            Add-Content -Path $p -Value $codeBlock -Encoding UTF8
        }
    }

    # Write psmgr-gui.cmd shims
    $guiShim = "@echo off`r`nchcp 65001 >nul`r`nstart powershell.exe -WindowStyle Hidden -NoProfile -ExecutionPolicy Bypass -File `"$Script:ROOT_PATH\gui.ps1`"`r`n"
    Set-Content -Path "$Script:USER_BIN_PATH\psmgr-gui.cmd" -Value $guiShim -Encoding ASCII
    if (Test-Path $Script:LOCAL_BIN_PATH) {
        Set-Content -Path "$Script:LOCAL_BIN_PATH\psmgr-gui.cmd" -Value $guiShim -Encoding ASCII
    }
}
